import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const projectRoot = new URL('../', import.meta.url);
const iconDirectory = new URL('../assets/blessings/', import.meta.url);
const outputFile = new URL('../blessing-icon-data.js', import.meta.url);
const iconFiles = (await readdir(iconDirectory)).filter(file => file.endsWith('.png')).sort();
const entries = {};

for (const file of iconFiles) {
  const bytes = await readFile(new URL(file, iconDirectory));
  entries[`assets/blessings/${file}`] = `data:image/png;base64,${bytes.toString('base64')}`;
}

const banner = '// Generated by scripts/generate-blessing-icon-data.mjs.\n';
await writeFile(outputFile, `${banner}window.BLESSING_ICON_DATA = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`Wrote ${iconFiles.length} icons to ${relative(process.cwd(), outputFile.pathname) || join('blessing-icon-data.js')}`);
